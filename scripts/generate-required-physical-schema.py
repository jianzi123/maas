"""Generate read-only FC-M object/key constants; never connect to a database."""
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
manifest = json.loads((ROOT / 'docs/contracts/agent-runtime/fc1-20261126/required-migrations.json').read_text(encoding='utf-8'))
tables, keys = [], []

def split_definitions(body):
    result, start, depth, quoted = [], 0, 0, False
    for index, char in enumerate(body):
        if char == "'":
            quoted = not quoted
        elif not quoted:
            if char == '(':
                depth += 1
            elif char == ')':
                depth -= 1
            elif char == ',' and depth == 0:
                result.append(body[start:index].strip())
                start = index + 1
    result.append(body[start:].strip())
    return result

for migration in manifest['migrations']:
    sql = (ROOT / migration['file']).read_text(encoding='utf-8')
    found = set()
    for match in re.finditer(r'CREATE TABLE IF NOT EXISTS (\w+)\s*\((.*?)\)\s*ENGINE=InnoDB', sql, re.S | re.I):
        table, body = match.groups()
        found.add(table)
        tables.append(table)
        for definition in split_definitions(body):
            primary = re.match(r'PRIMARY KEY\s*\(([^)]+)\)', definition, re.I)
            unique = re.match(r'UNIQUE KEY (\w+)\s*\(([^)]+)\)', definition, re.I)
            if primary:
                keys.append((table, 'PRIMARY', primary.group(1).split(',')))
            elif unique:
                keys.append((table, unique.group(1), unique.group(2).split(',')))
            elif not re.match(r'(KEY|INDEX|CHECK|CONSTRAINT|FOREIGN)\b', definition, re.I):
                column = definition.split()[0]
                if re.search(r'\bPRIMARY KEY\b', definition, re.I):
                    keys.append((table, 'PRIMARY', [column]))
                elif re.search(r'\bUNIQUE\b', definition, re.I):
                    keys.append((table, column, [column]))
    assert found == set(migration['physical_tables']), (migration['file'], found)

views = ['release_history_directory', 'release_history_projection', 'release_history_completeness']
journals = ['kernel_schema_migrations', 'release_schema_migrations', 'product_schema_migrations']
keys += [(name, 'PRIMARY', ['version']) for name in journals]
out = ['// Code generated by scripts/generate-required-physical-schema.py; DO NOT EDIT.',
       'package app', '', 'var requiredPhysicalObjects = []physicalObject{']
for name in sorted(set(tables + journals)):
    out.append(f'\t{{Name: "{name}", Kind: "BASE TABLE"}},')
for name in views:
    out.append(f'\t{{Name: "{name}", Kind: "VIEW"}},')
out += ['}', '', 'var requiredUniqueIndexes = []physicalUniqueIndex{']
for table, name, columns in sorted(keys):
    values = ','.join(json.dumps(column.strip()) for column in columns)
    out.append(f'\t{{Table: "{table}", Name: "{name}", Columns: []string{{{values}}}}},')
out += ['}', '']
(ROOT / 'internal/app/schema_physical_inventory.go').write_text('\n'.join(out), encoding='utf-8', newline='\n')
print(json.dumps({'objects': len(set(tables + journals)) + len(views), 'unique_indexes': len(keys)}))
